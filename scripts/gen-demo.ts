/**
 * Generates database/demo.sql from scripts/demo-data.ts. Dates are written as expressions
 * relative to UTC_TIMESTAMP(3), so the scenarios stay inside (or outside) the return windows
 * whenever the reviewer boots the containers. Run with: npx tsx scripts/gen-demo.ts
 */
import fs from 'node:fs';
import bcrypt from 'bcryptjs';
import { SHIPPING, orders, requests, users, type Age, type Req, type ReqItem } from './demo-data';

const PASSWORD = 'rma-demo-pass';

function sqlDate(age: Age | null): string {
  if (age === null) return 'NULL';
  const byDays = `DATE_SUB(UTC_TIMESTAMP(3), INTERVAL ${age.days} DAY)`;
  return age.months ? `DATE_SUB(${byDays}, INTERVAL ${age.months} MONTH)` : byDays;
}

function str(value: string | null | undefined): string {
  if (value === null || value === undefined) return 'NULL';
  return `'${value.replaceAll("'", "''")}'`;
}

function json(value: unknown): string {
  return value === undefined ? 'NULL' : str(JSON.stringify(value));
}

function orderOf(req: Req) {
  return orders.find((o) => o.id === req.order)!;
}

function unitPriceOf(req: Req, item: ReqItem) {
  return orderOf(req).items.find((i) => i.id === item.orderItem)!;
}

/** Per-line refund: approved units x unit price x inspection percentage. */
function itemFinalMinor(req: Req, item: ReqItem): number | null {
  if (item.decision === 'REJECTED') return 0;
  if (item.decision !== 'APPROVED') return null;
  const pct =
    item.percentage ?? (item.inspection === 'NOT_RECEIVED' ? 0 : item.inspection === 'AS_DECLARED' ? 100 : null);
  if (pct === null) return null;
  const baseMinor = Math.round((item.approved ?? item.requested) * unitPriceOf(req, item).price * 100);
  return Math.round((baseMinor * pct) / 100);
}

function requestTotalMinor(req: Req): number {
  const gross = req.items.reduce((sum, i) => sum + (itemFinalMinor(req, i) ?? 0), 0);
  return Math.max(0, gross - (req.payer === 'CUSTOMER' ? Math.round(SHIPPING * 100) : 0));
}

function build(hash: string): string {
  const out: string[] = [];
  out.push('-- Generated by scripts/gen-demo.ts (do not edit by hand).');
  out.push('-- Demo data for the RMA take-home assignment. Requires prisma/migrations/0001_init.');
  out.push('-- Password for every account: ' + PASSWORD);
  out.push('SET NAMES utf8mb4;');
  out.push('START TRANSACTION;');
  out.push('');
  out.push('-- Re-runnable: clear any previous demo rows first.');
  out.push('DELETE FROM `Notification`; DELETE FROM `OutboxEvent`; DELETE FROM `RequestHistory`;');
  out.push('DELETE FROM `RefundAttempt`; DELETE FROM `Refund`; DELETE FROM `Appeal`; DELETE FROM `ReturnItem`;');
  out.push('DELETE FROM `ReturnRequest`; DELETE FROM `OrderItem`; DELETE FROM `Order`;');
  out.push('DELETE FROM `Session`; DELETE FROM `User`;');
  out.push('');

  out.push('-- Four roles, two customers');
  out.push('INSERT INTO `User` (`id`, `username`, `displayName`, `passwordHash`, `role`, `createdAt`) VALUES');
  out.push(
    users
      .map(
        (u) =>
          `(${str(u.id)}, ${str(u.username)}, ${str(u.displayName)}, ${str(hash)}, ${str(u.role)}, DATE_SUB(UTC_TIMESTAMP(3), INTERVAL 90 DAY))`,
      )
      .join(',\n') + ';',
  );
  out.push('');

  out.push('-- Orders and payments belong to external systems; these rows are the read-only demo copy.');
  out.push(
    'INSERT INTO `Order` (`id`, `orderNumber`, `customerId`, `status`, `paymentMethod`, `currency`, `placedAt`, `deliveredAt`, `originalPaymentRef`, `createdAt`) VALUES',
  );
  out.push(
    orders
      .map(
        (o) =>
          `(${str(o.id)}, ${str(o.number)}, ${str(o.customer)}, ${str(o.status ?? 'DELIVERED')}, ${str(o.paymentMethod)}, ${str(o.currency)}, ${sqlDate(o.placed)}, ${sqlDate(o.delivered)}, ${str(o.paymentRef)}, ${sqlDate(o.placed)})`,
      )
      .join(',\n') + ';',
  );
  out.push('');

  out.push('INSERT INTO `OrderItem` (`id`, `orderId`, `productId`, `productName`, `quantity`, `unitPrice`, `warrantyMonths`) VALUES');
  out.push(
    orders
      .flatMap((o) =>
        o.items.map(
          (i) =>
            `(${str(i.id)}, ${str(o.id)}, ${str(i.sku)}, ${str(i.name)}, ${i.qty}, ${i.price.toFixed(2)}, ${i.warrantyMonths})`,
        ),
      )
      .join(',\n') + ';',
  );
  out.push('');

  out.push('-- One request per implemented state');
  out.push(
    'INSERT INTO `ReturnRequest` (`id`, `reference`, `customerId`, `orderId`, `status`, `overallReason`, `shippingPaidBy`, `returnShippingCost`, `notes`, `submittedAt`, `reviewedById`, `reviewedAt`, `createdAt`, `updatedAt`) VALUES',
  );
  out.push(
    requests
      .map((r) => {
        const created = r.submitted ?? r.created;
        return `(${str(r.id)}, ${str(r.reference)}, ${str(r.customer)}, ${str(r.order)}, ${str(r.status)}, ${str(r.overallReason)}, ${str(r.payer)}, ${SHIPPING.toFixed(2)}, ${str(r.notes ?? null)}, ${r.submitted ? sqlDate(r.submitted) : 'NULL'}, ${str(r.reviewer ?? null)}, ${r.reviewed ? sqlDate(r.reviewed) : 'NULL'}, ${sqlDate(created)}, ${sqlDate(r.created)})`;
      })
      .join(',\n') + ';',
  );
  out.push('');

  out.push('-- Line level decisions, receipt, inspection and refund amounts');
  out.push(
    'INSERT INTO `ReturnItem` (`id`, `returnRequestId`, `orderItemId`, `productName`, `requestedQuantity`, `reason`, `approvedQuantity`, `decision`, `decisionReason`, `decidedById`, `decidedAt`, `receiptStatus`, `inspectionResult`, `inspectionComment`, `inspectedById`, `inspectedAt`, `refundPercentage`, `refundableBase`, `estimatedRefund`, `finalRefundAmount`) VALUES',
  );
  out.push(
    requests
      .flatMap((r) =>
        r.items.map((item) => {
          const oi = unitPriceOf(r, item);
          const base = ((item.approved ?? item.requested) * oi.price).toFixed(2);
          const finalMinor = itemFinalMinor(r, item);
          const inspected = Boolean(item.inspection && item.inspection !== 'PENDING');
          return `(${str(item.id)}, ${str(r.id)}, ${str(item.orderItem)}, ${str(oi.name)}, ${item.requested}, ${str(item.reason)}, ${item.approved ?? 'NULL'}, ${str(item.decision)}, ${str(item.rejectReason ?? null)}, ${str(r.reviewer ?? null)}, ${r.reviewed ? sqlDate(r.reviewed) : 'NULL'}, ${str(item.receipt ?? 'NOT_APPLICABLE')}, ${str(item.inspection ?? 'PENDING')}, ${str(item.inspectionComment ?? null)}, ${inspected ? str('u-lee') : 'NULL'}, ${inspected ? sqlDate({ days: 5 }) : 'NULL'}, ${item.percentage ?? 'NULL'}, ${item.decision === 'APPROVED' ? base : 'NULL'}, ${item.decision === 'APPROVED' ? base : 'NULL'}, ${finalMinor === null ? 'NULL' : (finalMinor / 100).toFixed(2)})`;
        }),
      )
      .join(',\n') + ';',
  );
  out.push('');

  const appeals = requests.filter((r) => r.appeal);
  out.push('-- Appeals: at most one per request, never reviewed by the operator who rejected it');
  out.push(
    'INSERT INTO `Appeal` (`id`, `returnRequestId`, `customerId`, `comment`, `status`, `reviewedById`, `reviewReason`, `createdAt`, `reviewedAt`) VALUES',
  );
  out.push(
    appeals
      .map(
        (r) =>
          `(${str(r.appeal!.id)}, ${str(r.id)}, ${str(r.customer)}, ${str(r.appeal!.comment)}, ${str(r.appeal!.status)}, ${str(r.appeal!.reviewer ?? null)}, ${str(r.appeal!.reviewReason ?? null)}, ${sqlDate(r.appeal!.created)}, ${r.appeal!.reviewed ? sqlDate(r.appeal!.reviewed) : 'NULL'})`,
      )
      .join(',\n') + ';',
  );
  out.push('');

  const withRefund = requests.filter((r) => r.refund);
  out.push('-- Refunds: one logical payout per request, guarded by the unique idempotency key');
  out.push(
    'INSERT INTO `Refund` (`id`, `returnRequestId`, `orderId`, `amount`, `currency`, `paymentMethod`, `idempotencyKey`, `providerRef`, `status`, `failureReason`, `initiatedById`, `initiatedAt`, `settledAt`, `createdAt`, `updatedAt`) VALUES',
  );
  out.push(
    withRefund
      .map((r) => {
        const order = orderOf(r);
        const refund = r.refund!;
        const initiated = refund.attempts.length ? sqlDate(refund.attempts[0].at) : 'NULL';
        const settled =
          refund.status === 'SUCCEEDED' ? sqlDate(refund.attempts[refund.attempts.length - 1].at) : 'NULL';
        return `(${str(refund.id)}, ${str(r.id)}, ${str(order.id)}, ${(requestTotalMinor(r) / 100).toFixed(2)}, ${str(order.currency)}, ${str(order.paymentMethod)}, ${str('RFN-' + r.reference)}, ${str(refund.providerRef ?? null)}, ${str(refund.status)}, ${str(refund.failureReason ?? null)}, ${refund.attempts.length ? str('u-max') : 'NULL'}, ${initiated}, ${settled}, ${sqlDate(refund.at)}, ${sqlDate(refund.at)})`;
      })
      .join(',\n') + ';',
  );
  out.push('');

  out.push('-- Every provider call is kept, including declined and unanswered attempts');
  out.push(
    'INSERT INTO `RefundAttempt` (`id`, `refundId`, `attemptNumber`, `requestKey`, `outcome`, `providerCode`, `providerMessage`, `latencyMs`, `createdAt`) VALUES',
  );
  out.push(
    withRefund
      .flatMap((r) =>
        r.refund!.attempts.map((a, index) => {
          const refund = r.refund!;
          return `(${str(refund.id + '-a' + (index + 1))}, ${str(refund.id)}, ${index + 1}, ${str('RFN-' + r.reference)}, ${str(a.outcome)}, ${str(a.code)}, ${str(a.message)}, ${a.latency}, ${sqlDate(a.at)})`;
        }),
      )
      .join(',\n') + ';',
  );
  out.push('');

  out.push('-- Audit trail: who did what, when and why');
  out.push(
    'INSERT INTO `RequestHistory` (`id`, `returnRequestId`, `actorId`, `actorLabel`, `action`, `fromStatus`, `toStatus`, `detail`, `reason`, `createdAt`) VALUES',
  );
  out.push(
    requests
      .flatMap((r) =>
        r.history.map(
          (h, index) =>
            `(${str(r.id + '-h' + (index + 1))}, ${str(r.id)}, ${str(h.actor)}, ${str(h.actorLabel)}, ${str(h.action)}, ${str(h.from)}, ${str(h.to)}, ${json(h.detail)}, ${str(h.reason ?? null)}, ${sqlDate(h.at)})`,
        ),
      )
      .join(',\n') + ';',
  );
  out.push('');

  out.push('-- Outbox events, already dispatched to the notification channel');
  out.push(
    'INSERT INTO `OutboxEvent` (`id`, `returnRequestId`, `type`, `payload`, `createdAt`, `processedAt`, `attempts`) VALUES',
  );
  out.push(
    requests
      .flatMap((r) =>
        r.history.map(
          (h, index) =>
            `(${str(r.id + '-e' + (index + 1))}, ${str(r.id)}, ${str('request.' + h.action)}, ${json({ action: h.action, fromStatus: h.from, toStatus: h.to, actorLabel: h.actorLabel, reason: h.reason ?? null })}, ${sqlDate(h.at)}, ${sqlDate(h.at)}, 1)`,
        ),
      )
      .join(',\n') + ';',
  );
  out.push('');

  out.push('-- In-app alerts so the notification screen is populated on first login');
  out.push(
    'INSERT INTO `Notification` (`id`, `userId`, `returnRequestId`, `title`, `body`, `channel`, `readAt`, `createdAt`) VALUES',
  );
  out.push(
    requests
      .flatMap((r) => {
        const last = r.history[r.history.length - 1];
        const targets = [r.customer, ...(r.reviewer ? [r.reviewer] : []), 'u-lee', 'u-max'];
        return targets.map(
          (userId, index) =>
            `(${str(r.id + '-n' + index)}, ${str(userId)}, ${str(r.id)}, ${str(r.reference + ': ' + last.action.replaceAll('_', ' '))}, ${str('Status is now ' + r.status.replaceAll('_', ' ').toLowerCase() + (last.reason ? '. ' + last.reason : ''))}, 'in_app', NULL, ${sqlDate(last.at)})`,
        );
      })
      .join(',\n') + ';',
  );
  out.push('');
  out.push('COMMIT;');
  out.push('');
  return out.join('\n');
}

const hash = bcrypt.hashSync(PASSWORD, 10);
fs.writeFileSync(new URL('../database/demo.sql', import.meta.url), build(hash), 'utf8');
console.log('wrote database/demo.sql');
